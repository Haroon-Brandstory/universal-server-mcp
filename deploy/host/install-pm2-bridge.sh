#!/usr/bin/env bash
# Run on the DigitalOcean VPS as root (or sudo).
# Installs /usr/local/sbin/bsd-pm2, opens PM2_HOME to MCP uid 10001, prints compose env.
# MCP container MUST stay user 10001:10001 so /data (oauth-store) stays writable.
set -euo pipefail

APP_USER="${BSD_PM2_USER:-bsdglobal}"
MCP_UID=10001
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="${REPO_ROOT}/deploy/host/bsd-pm2"
DST=/usr/local/sbin/bsd-pm2

if [[ ! -f "${SRC}" ]]; then
  echo "missing ${SRC}" >&2
  exit 1
fi

if ! id "${APP_USER}" >/dev/null 2>&1; then
  echo "user ${APP_USER} not found" >&2
  exit 1
fi

APP_HOME="$(getent passwd "${APP_USER}" | cut -d: -f6)"
APP_GID="$(id -g "${APP_USER}")"

PM2_PATH="$(
  sudo -u "${APP_USER}" -H bash -lc 'command -v pm2' 2>/dev/null || true
)"
if [[ -z "${PM2_PATH}" ]]; then
  echo "pm2 not found for ${APP_USER}. Install pm2 or fix nvm PATH." >&2
  exit 1
fi
NODE_BIN_DIR="$(dirname "${PM2_PATH}")"

install -m 0755 "${SRC}" "${DST}"

PM2_DIR="${APP_HOME}/.pm2"
mkdir -p "${PM2_DIR}"
# Let container uid 10001 use the host PM2 daemon socket/files
if command -v setfacl >/dev/null 2>&1; then
  setfacl -R -m "u:${MCP_UID}:rwX" "${PM2_DIR}" || true
  setfacl -R -d -m "u:${MCP_UID}:rwX" "${PM2_DIR}" || true
else
  chmod -R g+rwX "${PM2_DIR}" || true
fi
# Ensure group sticky for new PM2 files when possible
chgrp -R "${APP_GID}" "${PM2_DIR}" 2>/dev/null || true

COMPOSE_ENV="${REPO_ROOT}/deploy/docker/.env.pm2"
cat >"${COMPOSE_ENV}" <<EOF
# Generated by deploy/host/install-pm2-bridge.sh — compose interpolation
# Do NOT set MCP_HOST_UID as container user — keep 10001 for /data oauth-store.
MCP_HOST_GID=${APP_GID}
MCP_HOST_NODE_BIN=${NODE_BIN_DIR}
MCP_HOST_HOME=${APP_HOME}
EOF
chmod 644 "${COMPOSE_ENV}"

# Repair oauth/audit volume if previous bad UID switch left it unwritable
if [[ -x "${REPO_ROOT}/deploy/host/repair-mcp-data-perms.sh" ]]; then
  bash "${REPO_ROOT}/deploy/host/repair-mcp-data-perms.sh" || true
fi

echo "Installed ${DST}"
echo "Wrote ${COMPOSE_ENV}"
echo
echo "Add to /etc/bsd-global-mcp/env (if missing):"
echo "  MCP_PM2_BIN=/usr/local/sbin/bsd-pm2"
echo "  MCP_NPM_BIN=/host-nodejs/bin/npm"
echo "  MCP_PM2_NEXTJS_NAME=frontend-nextjs"
echo "  MCP_PM2_STRAPI_NAME=strapi-backend"
echo
echo "Recreate MCP (user stays 10001):"
echo "  cd ${REPO_ROOT}"
echo "  docker compose -f deploy/docker/docker-compose.bsd-global.yml --env-file deploy/docker/.env.pm2 up -d --build"
echo
echo "Smoke:"
echo "  docker exec bsd-global-mcp /usr/local/sbin/bsd-pm2 jlist"
echo "  curl -sS -X POST https://mcp.brandstoryglobal.com/token -d 'grant_type=refresh_token&refresh_token=x&client_id=global-server-mcp-grok'"
