#!/usr/bin/env bash
# Host install: ACL on ~/.pm2 + ctl dir + systemd path units for approved restarts.
# MCP container stays uid 10001 (OAuth /data). Restarts go: touch ctl → systemd → bsdglobal pm2.
set -euo pipefail

APP_USER="${BSD_PM2_USER:-bsdglobal}"
MCP_UID=10001
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CTL_DIR=/var/lib/bsd-mcp/ctl

if ! id "${APP_USER}" >/dev/null 2>&1; then
  echo "user ${APP_USER} not found" >&2
  exit 1
fi

if ! command -v setfacl >/dev/null 2>&1; then
  echo "Installing acl package (needed for optional PM2_HOME ACL)..."
  apt-get update -qq && apt-get install -y -qq acl || true
fi

APP_HOME="$(getent passwd "${APP_USER}" | cut -d: -f6)"
APP_GID="$(id -g "${APP_USER}")"
PM2_DIR="${APP_HOME}/.pm2"
mkdir -p "${PM2_DIR}"
chown "${APP_USER}:${APP_GID}" "${PM2_DIR}" || true

if command -v setfacl >/dev/null 2>&1; then
  setfacl -R -m "u:${MCP_UID}:rwX" "${PM2_DIR}" || true
  setfacl -R -d -m "u:${MCP_UID}:rwX" "${PM2_DIR}" || true
else
  echo "WARN: setfacl still missing — status probes may fail; restarts use ctl/systemd"
fi

install -m 0755 "${REPO_ROOT}/deploy/host/bsd-restart-nextjs" /usr/local/sbin/bsd-restart-nextjs
install -m 0755 "${REPO_ROOT}/deploy/host/bsd-restart-strapi" /usr/local/sbin/bsd-restart-strapi
install -m 0755 "${REPO_ROOT}/deploy/host/bsd-mcp-ctl-handle" /usr/local/sbin/bsd-mcp-ctl-handle
install -m 0755 "${REPO_ROOT}/deploy/host/bsd-mcp-request" /usr/local/sbin/bsd-mcp-request

mkdir -p "${CTL_DIR}"
chown "${MCP_UID}:${MCP_UID}" "${CTL_DIR}"
chmod 775 "${CTL_DIR}"

for unit in \
  bsd-mcp-restart-nextjs.path \
  bsd-mcp-restart-nextjs.service \
  bsd-mcp-restart-strapi.path \
  bsd-mcp-restart-strapi.service
do
  install -m 0644 "${REPO_ROOT}/deploy/systemd/${unit}" "/etc/systemd/system/${unit}"
done

systemctl daemon-reload
systemctl enable --now bsd-mcp-restart-nextjs.path
systemctl enable --now bsd-mcp-restart-strapi.path

COMPOSE_ENV="${REPO_ROOT}/deploy/docker/.env.pm2"
cat >"${COMPOSE_ENV}" <<EOF
# Generated by deploy/host/install-pm2-bridge.sh
MCP_HOST_HOME=${APP_HOME}
MCP_PM2_NEXTJS_NAME=frontend-nextjs
MCP_PM2_STRAPI_NAME=strapi-backend
EOF
chmod 644 "${COMPOSE_ENV}"

if [[ -x "${REPO_ROOT}/deploy/host/repair-mcp-data-perms.sh" ]]; then
  bash "${REPO_ROOT}/deploy/host/repair-mcp-data-perms.sh" || true
fi

echo "Installed host PM2 restart bridge (ctl + systemd)."
echo "  ctl dir: ${CTL_DIR}"
echo "  scripts: /usr/local/sbin/bsd-restart-{nextjs,strapi}"
echo
echo "NOW (live title): as ${APP_USER} run:  pm2 restart frontend-nextjs"
echo "  or:  pm2 restart 0"
echo
echo "Recreate MCP:"
echo "  cd ${REPO_ROOT}"
echo "  docker compose -f deploy/docker/docker-compose.bsd-global.yml --env-file deploy/docker/.env.pm2 up -d --build"
echo
echo "Smoke after recreate:"
echo "  docker exec bsd-global-mcp /usr/local/sbin/bsd-mcp-request nextjs"
